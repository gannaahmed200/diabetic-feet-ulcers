/* ---------------------- Main ---------------------- */
int main(void)
{
    HAL_Init();
    SystemClock_Config();
    DWT_Init();

    MX_GPIO_Init();
    MX_ADC1_Init();
    MX_USART1_UART_Init();

    const char header[] =
        "timestamp_ms,heel,midfoot,forefoot,temp1_C,temp2_C,humidity_pct,risk_score\r\n";
    HAL_UART_Transmit(&huart1, (uint8_t *)header, strlen(header), HAL_MAX_DELAY);

    while (1)
    {
        uint32_t now = HAL_GetTick();

        if ((now - lastSampleTick) >= SAMPLE_INTERVAL_MS)
        {
            lastSampleTick = now;

            SensorSnapshot_t snap;
            snap.pressure       = readPressureSensors();
            snap.temperature    = readTemperatureSensors();
            snap.humidityValid  = readDHT11(&snap.humidity);
            snap.riskScore      = computeRiskScore(&snap);

            sendSnapshotCSV(&snap);
            checkAlerts(&snap);
        }
    }
}

/* ---------------------- Microsecond delay (DWT cycle counter) ---------------------- */
static void DWT_Init(void)
{
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0;
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
}

static void delay_us(uint32_t us)
{
    uint32_t start = DWT->CYCCNT;
    uint32_t ticks = us * (SystemCoreClock / 1000000U);
    while ((DWT->CYCCNT - start) < ticks) { }
}

/* ---------------------- ADC Reading ---------------------- */
static uint16_t readADCChannel(uint32_t channel)
{
    ADC_ChannelConfTypeDef sConfig = {0};
    sConfig.Channel      = channel;
    sConfig.Rank         = ADC_REGULAR_RANK_1;
    sConfig.SamplingTime = ADC_SAMPLETIME_55CYCLES_5;
    HAL_ADC_ConfigChannel(&hadc1, &sConfig);

    HAL_ADC_Start(&hadc1);
    HAL_ADC_PollForConversion(&hadc1, HAL_MAX_DELAY);
    uint16_t value = HAL_ADC_GetValue(&hadc1);
    HAL_ADC_Stop(&hadc1);

    return value;
}

static PressureData_t readPressureSensors(void)
{
    PressureData_t p;
    p.heel     = readADCChannel(ADC_CHANNEL_0);
    p.midfoot  = readADCChannel(ADC_CHANNEL_1);
    p.forefoot = readADCChannel(ADC_CHANNEL_2);
    return p;
}

static TemperatureData_t readTemperatureSensors(void)
{
    TemperatureData_t t;
    t.zone1 = adcToCelsius(readADCChannel(ADC_CHANNEL_3));
    t.zone2 = adcToCelsius(readADCChannel(ADC_CHANNEL_4));
    return t;
}

static float adcToCelsius(uint16_t adcValue)
{
    /* LM35: 10 mV/°C, 3.3V reference on STM32 (not 5V like the Arduino version),
     * 12-bit ADC (0-4095). */
    float voltage = (adcValue * 3.3f) / 4095.0f;
    return voltage * 100.0f;
}

/* ---------------------- DHT11 (bit-banged, PB0) ---------------------- */
static void DHT11_SetPinOutput(void)
{
    GPIO_InitTypeDef gpio = {0};
    gpio.Pin   = GPIO_PIN_0;
    gpio.Mode  = GPIO_MODE_OUTPUT_PP;
    gpio.Pull  = GPIO_NOPULL;
    gpio.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOB, &gpio);
}

static void DHT11_SetPinInput(void)
{
    GPIO_InitTypeDef gpio = {0};
    gpio.Pin  = GPIO_PIN_0;
    gpio.Mode = GPIO_MODE_INPUT;
    gpio.Pull = GPIO_PULLUP;
    HAL_GPIO_Init(GPIOB, &gpio);
}

static uint8_t readDHT11(float *humidity)
{
    uint8_t data[5] = {0};

    /* --- Start signal --- */
    DHT11_SetPinOutput();
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET);
    HAL_Delay(18);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_SET);
    delay_us(30);
    DHT11_SetPinInput();

    /* --- Wait for sensor response (with timeouts so we never hang) --- */
    uint32_t timeout = 0;
    while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_0) == GPIO_PIN_SET) {
        if (++timeout > 1000) return 0;
        delay_us(1);
    }
    timeout = 0;
    while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_0) == GPIO_PIN_RESET) {
        if (++timeout > 1000) return 0;
        delay_us(1);
    }
    timeout = 0;
    while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_0) == GPIO_PIN_SET) {
        if (++timeout > 1000) return 0;
        delay_us(1);
    }

    /* --- Read 40 data bits --- */
    for (uint8_t i = 0; i < 40; i++)
    {
        timeout = 0;
        while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_0) == GPIO_PIN_RESET) {
            if (++timeout > 1000) return 0;
            delay_us(1);
        }

        delay_us(40); /* sample mid-bit: high >28us => '1', shorter => '0' */
        uint8_t bit = (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_0) == GPIO_PIN_SET) ? 1 : 0;

        timeout = 0;
        while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_0) == GPIO_PIN_SET) {
            if (++timeout > 1000) break;
            delay_us(1);
        }

        data[i / 8] <<= 1;
        data[i / 8] |= bit;
    }

    uint8_t checksum = data[0] + data[1] + data[2] + data[3];
    if (checksum != data[4]) return 0;

    *humidity = (float)data[0];
    return 1;
}

/* ---------------------- Risk Fusion (same weighted model as the Arduino version) ---------------------- */
static uint8_t computeRiskScore(const SensorSnapshot_t *snap)
{
    uint16_t score = 0;

    uint16_t maxPressure = snap->pressure.heel;
    if (snap->pressure.midfoot  > maxPressure) maxPressure = snap->pressure.midfoot;
    if (snap->pressure.forefoot > maxPressure) maxPressure = snap->pressure.forefoot;
    if (maxPressure > PRESSURE_ALERT_ADC) score += 40;

    float tempDiff = fabsf(snap->temperature.zone1 - snap->temperature.zone2);
    if (tempDiff > TEMP_DIFF_ALERT_C) score += 40;

    if (snap->humidityValid && snap->humidity > HUMIDITY_ALERT_PCT) score += 20;

    if (score > 100) score = 100;
    return (uint8_t)score;
}

/* ---------------------- Alerting ---------------------- */
static void checkAlerts(const SensorSnapshot_t *snap)
{
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_8,
                       (snap->riskScore >= RISK_ALERT_SCORE) ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

/* ---------------------- CSV Output over USART1 ---------------------- */
static void sendSnapshotCSV(const SensorSnapshot_t *snap)
{
    char line[128];
    int len = snprintf(line, sizeof(line),
                        "%lu,%u,%u,%u,%.2f,%.2f,%.1f,%u\r\n",
                        (unsigned long)HAL_GetTick(),
                        snap->pressure.heel, snap->pressure.midfoot, snap->pressure.forefoot,
                        snap->temperature.zone1, snap->temperature.zone2,
                        snap->humidityValid ? snap->humidity : -1.0f,
                        snap->riskScore);

    HAL_UART_Transmit(&huart1, (uint8_t *)line, len, HAL_MAX_DELAY);
}

