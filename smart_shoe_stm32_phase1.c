#include "main.h"
#include <stdio.h>
#include <string.h>
#include <math.h>

ADC_HandleTypeDef  hadc1;
UART_HandleTypeDef huart1;

/* ---------------------- Timing ---------------------- */
#define SAMPLE_INTERVAL_MS   500U
static uint32_t lastSampleTick = 0;

/* ---------------------- Calibration / Thresholds ---------------------- */
#define TEMP_DIFF_ALERT_C    2.2f
#define PRESSURE_ALERT_ADC   3300   /* 12-bit ADC (0-4095), tune while simulating */
#define HUMIDITY_ALERT_PCT   70.0f
#define RISK_ALERT_SCORE     60

/* ---------------------- Data Structures ---------------------- */
typedef struct {
    uint16_t heel;
    uint16_t midfoot;
    uint16_t forefoot;
} PressureData_t;

typedef struct {
    float zone1;
    float zone2;
} TemperatureData_t;

typedef struct {
    PressureData_t    pressure;
    TemperatureData_t temperature;
    float             humidity;
    uint8_t           humidityValid;
    uint8_t           riskScore;
} SensorSnapshot_t;

/* ---------------------- Function Prototypes ---------------------- */
static void     DWT_Init(void);
static void     delay_us(uint32_t us);

static uint16_t readADCChannel(uint32_t channel);
static PressureData_t    readPressureSensors(void);
static TemperatureData_t readTemperatureSensors(void);
static float    adcToCelsius(uint16_t adcValue);

static void     DHT11_SetPinOutput(void);
static void     DHT11_SetPinInput(void);
static uint8_t  readDHT11(float *humidity);

static uint8_t  computeRiskScore(const SensorSnapshot_t *snap);
static void     checkAlerts(const SensorSnapshot_t *snap);
static void     sendSnapshotCSV(const SensorSnapshot_t *snap);

